require 'json'
require 'cocoapods-imy-bin/helpers/xcframework_builder'

module CBin
  # Converts a source podspec into the binary podspec that consumes the
  # XCFramework ZIP produced by CBin::XCFrameworkBuilder.
  module XCFrameworkSpec
    # Attributes that only make sense when compiling sources.
    SOURCE_KEYS = %w[
      source_files public_header_files private_header_files project_header_files
      exclude_files preserve_paths module_map header_dir header_mappings_dir
      resource_bundles resources prepare_command script_phases
      vendored_frameworks vendored_framework vendored_libraries vendored_library
    ].freeze
    PLATFORM_KEYS = %w[ios osx tvos watchos visionos].freeze

    module_function

    def create(code_spec, download_url:, sha256: nil)
      hash = deep_copy(code_spec.to_hash)
      unsupported = vendored_binaries(hash) + plain_resources(code_spec)
      unless unsupported.empty?
        raise Pod::Informative, "#{code_spec.name} 含有 #{unsupported.join(', ')}，暂不支持转换为 XCFramework 二进制组件."
      end

      strip_source_attributes!(hash)
      hash['source'] = { 'http' => download_url, 'type' => 'zip' }
      hash['source']['sha256'] = sha256 if sha256
      hash['vendored_frameworks'] = "#{code_spec.name}.xcframework"
      bundles = XCFrameworkBuilder.resource_bundle_names(code_spec)
      hash['resources'] = bundles.map { |name| "#{name}.bundle" } unless bundles.empty?
      # The binary only contains the iOS slices.
      hash['platforms'] = { 'ios' => hash.dig('platforms', 'ios') }.compact
      hash['platforms'] = { 'ios' => nil } if hash['platforms'].empty?
      hash['description'] = "Binary XCFramework generated by cocoapods-imy-bin.\n#{hash['description']}".strip

      Pod::Specification.from_hash(hash)
    end

    def strip_source_attributes!(hash)
      SOURCE_KEYS.each { |key| hash.delete(key) }
      PLATFORM_KEYS.each do |platform|
        next unless hash[platform].is_a?(Hash)

        SOURCE_KEYS.each { |key| hash[platform].delete(key) }
        hash.delete(platform) if hash[platform].empty?
      end
      # Keep subspecs so `pod 'Name/Sub'` still resolves; the root framework
      # carries every subspec's code.
      Array(hash['subspecs']).each { |subspec| strip_source_attributes!(subspec) }
      hash.delete('testspecs')
      hash.delete('appspecs')
    end

    # Loose `resources` are not part of the built framework; silently dropping
    # them would break the app at runtime, so require resource_bundles instead.
    def plain_resources(code_spec)
      [code_spec, *code_spec.recursive_subspecs].flat_map do |entry|
        entry.consumer(:ios).resources.empty? ? [] : ["#{entry.name} resources"]
      end
    end

    def vendored_binaries(hash, prefix = nil)
      found = []
      %w[vendored_frameworks vendored_framework vendored_libraries vendored_library].each do |key|
        found << [prefix, key].compact.join('/') unless Array(hash[key]).empty?
        PLATFORM_KEYS.each do |platform|
          next unless hash[platform].is_a?(Hash) && !Array(hash[platform][key]).empty?

          found << [prefix, "#{platform}.#{key}"].compact.join('/')
        end
      end
      Array(hash['subspecs']).each { |subspec| found.concat(vendored_binaries(subspec, subspec['name'])) }
      found
    end

    def deep_copy(value)
      JSON.parse(JSON.generate(value))
    end
  end
end
